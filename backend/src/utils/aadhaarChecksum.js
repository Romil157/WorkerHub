/**
 * Validates an Aadhaar number using the Verhoeff checksum algorithm.
 * @param {string} aadhaarStr - 12-digit Aadhaar number string
 * @returns {boolean}
 */
const validateVerhoeff = (aadhaarStr) => {
  if (!aadhaarStr || typeof aadhaarStr !== 'string') return false;
  
  // Strip spaces if present
  const sanitized = aadhaarStr.replace(/\s/g, '');
  
  // Aadhaar must be exactly 12 digits
  if (!/^\d{12}$/.test(sanitized)) return false;

  let c = 0;
  const invertedArray = sanitized.split('').reverse().map(Number);

  for (let i = 0; i < invertedArray.length; i++) {
    c = d[c][p[i % 8][invertedArray[i]]];
  }

  return c === 0;
};

module.exports = { validateVerhoeff };
